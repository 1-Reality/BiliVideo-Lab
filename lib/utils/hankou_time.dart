/// 漢口特別市时间：东经 114.3144478° 的视太阳时（真太阳时）
///
/// 平太阳时为 UTC+07:37:15.467479，再加上均时差。均时差按 Meeus《天文算法》
/// 第 28 章：太阳位置取 VSOP87（Meeus 附录三截断版），含 FK5 修正、IAU 1980
/// 章动主项与光行差，ΔT 取 69.2 秒。与 Meeus 例 28.a 相差 0.0002 秒。
///
/// 均时差每个 UTC 日只在零点算一次并缓存，日内线性插值，
/// 全年插值误差不超过 0.11 秒，低于秒级显示精度。
abstract final class HankouTime {
  static const _meanOffsetUs = 27435467479;
  static const _dayUs = 86400000000;
  static final _eotUsByDay = <int, double>{};

  /// UTC 微秒时间戳到漢口特別市时间的偏移，单位微秒
  static int offsetUs(int utcUs) {
    final day = utcUs ~/ _dayUs;
    final e0 = _eotUsByDay[day] ??= _eotUs(day);
    final e1 = _eotUsByDay[day + 1] ??= _eotUs(day + 1);
    return _meanOffsetUs +
        (e0 + (e1 - e0) * (utcUs - day * _dayUs) * (1 / _dayUs)).round();
  }

  /// Unix 日 [day] 的 UTC 零点的均时差，单位微秒
  static double _eotUs(int day) {
    // 自 J2000.0 起的儒略千年数（力学时）
    final tau = (day - 10957.5 + 69.2 / 86400) * (1 / 365250);
    final t = tau * 10;
    const arcsec = pi / 648000;
    const deg = pi / 180;

    final r = _series(_r, tau);
    final theta = _series(_l, tau) + pi;
    final lp = theta - (1.397 * t + 0.00031 * t * t) * deg;
    final sun = theta - 0.09033 * arcsec;
    final beta =
        -_series(_b, tau) + 0.03916 * arcsec * (cos(lp) - sin(lp));

    final om = (125.04452 - 1934.136261 * t) * deg;
    final ls = (280.4665 + 36000.7698 * t) * (2 * deg);
    final lm = (218.3165 + 481267.8813 * t) * (2 * deg);
    final dpsi =
        (-17.20 * sin(om) - 1.32 * sin(ls) - 0.23 * sin(lm) + 0.21 * sin(2 * om)) *
        arcsec;
    final eps =
        (84381.448 -
            46.8150 * t -
            0.00059 * t * t +
            0.001813 * t * t * t +
            9.20 * cos(om) +
            0.57 * cos(ls) +
            0.10 * cos(lm) -
            0.09 * cos(2 * om)) *
        arcsec;

    final lambda = sun + dpsi - 20.4898 * arcsec / r;
    final alpha = atan2(
      sin(lambda) * cos(eps) - tan(beta) * sin(eps),
      cos(lambda),
    );
    final l0 =
        (280.4664567 +
            tau *
                (360007.6982779 +
                    tau *
                        (0.03032028 +
                            tau *
                                (1 / 49931 +
                                    tau * (-1 / 15300 - tau / 2000000))))) *
        deg;
    // 均时差（弧度）归到 ±π，再按每弧度 86400/(2π) 秒换成微秒
    final e = (l0 - 0.0057183 * deg - alpha + dpsi * cos(eps)) % (2 * pi);
    return (e > pi ? e - 2 * pi : e) * (43200e6 / pi);
  }

  static double _series(List<List<double>> rows, double tau) {
    var sum = 0.0;
    var power = 1.0;
    for (final row in rows) {
      var s = 0.0;
      for (var i = 0; i < row.length; i += 3) {
        s += row[i] * cos(row[i + 1] + row[i + 2] * tau);
      }
      sum += s * power;
      power *= tau;
    }
    return sum * 1e-8;
  }

